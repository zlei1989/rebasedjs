/**
 * 「在新标签页打开」原语：差异页（含 Monaco 的对比界面）专用出口。
 *
 * 为什么需要它：差异页原本经路由跳转（web-koa 的 navigate / web-next 的 router.push）打开，
 * 当前页（变更列表、日志、历史、溯源、分支差异清单）会被整页顶掉——用户核对完一个
 * 文件想再看下一个，得先退回原页。改成新标签页后原页原地保留，且可多个文件各自开一个标签并排对照。
 *
 * 为什么不具名窗口（第二个参数给固定 name）：具名会把后续每次打开都复用到同一个标签，
 * 第二个文件就会顶掉第一个，与「并排对照」的目的相反，故固定 '_blank'。
 *
 * noopener：新标签页拿不到 window.opener，防止被打开的页面反向操控本页（与仓内打开 GitHub
 * 提交链接同一写法）。代价是返回句柄恒为 null——本函数不需要回写，故不返回。
 *
 * 相对路径直接可用：window.open 按当前 origin 解析，与路由跳转时的同一条路径串完全一致，
 * 调用方不必为「新标签页」额外拼绝对地址。
 */
export function openInNewTab(url: string): void {
  window.open(url, '_blank', 'noopener');
}
